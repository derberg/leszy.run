// Builds the supabase/config.toml of test slot n (see slot.js): the repo's own
// config with project_id suffixed "-s<n>" and every host port moved up by
// n x 100. scripts/test-slot.sh calls it on every run, so a slot always tracks
// the current config.toml.
//
// The repo's config.toml sets no ports, so the CLI defaults apply in slot 0.
// Those defaults are written out explicitly here (moved by the offset); a port
// config.toml does set, in any section, is moved too.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { SLOT_STEP } from './slot.js'

// The Supabase CLI's default host ports (`supabase init`, CLI 2.101).
export const DEFAULT_PORTS = [
  ['api', 'port', 54321],
  ['db', 'port', 54322],
  ['db', 'shadow_port', 54320],
  ['db.pooler', 'port', 54329],
  ['studio', 'port', 54323],
  ['inbucket', 'port', 54324],
  ['inbucket', 'smtp_port', 54325],
  ['inbucket', 'pop3_port', 54326],
  ['analytics', 'port', 54327],
  ['edge_runtime', 'inspector_port', 8083],
]

const HEADER = /^\s*\[([^\]]+)\]\s*(#.*)?$/
const PORT_LINE = /^(\s*)([A-Za-z_]*port)(\s*=\s*)(\d+)(.*)$/

/** config.toml text -> the slot's config.toml text. */
export function slotConfig(toml, slot) {
  if (!Number.isInteger(slot) || slot < 1) throw new Error(`slot must be an integer >= 1, got ${slot}`)
  const offset = slot * SLOT_STEP
  const lines = toml.split('\n')
  let section = ''
  let sawProjectId = false
  const seen = new Set() // "section.key" already present
  const headerAt = new Map() // section -> line index of its header

  for (let i = 0; i < lines.length; i++) {
    const h = lines[i].match(HEADER)
    if (h) {
      section = h[1].trim()
      headerAt.set(section, i)
      continue
    }
    if (section === '' && /^\s*project_id\s*=/.test(lines[i])) {
      lines[i] = lines[i].replace(/^(\s*project_id\s*=\s*")([^"]*)(".*)$/, (_, a, id, b) => `${a}${id}-s${slot}${b}`)
      sawProjectId = true
      continue
    }
    const p = lines[i].match(PORT_LINE)
    if (p) {
      lines[i] = `${p[1]}${p[2]}${p[3]}${Number(p[4]) + offset}${p[5]}`
      seen.add(`${section}.${p[2]}`)
    }
  }
  if (!sawProjectId) throw new Error('config.toml has no top-level project_id')

  // Defaults the file does not set: insert under an existing header, else append a section.
  const inserts = new Map() // header line index -> lines to add after it
  const appended = new Map() // section -> lines
  for (const [sec, key, base] of DEFAULT_PORTS) {
    if (seen.has(`${sec}.${key}`)) continue
    const line = `${key} = ${base + offset}`
    if (headerAt.has(sec)) {
      const at = headerAt.get(sec)
      inserts.set(at, [...(inserts.get(at) || []), line])
    } else {
      appended.set(sec, [...(appended.get(sec) || []), line])
    }
  }
  const out = []
  lines.forEach((l, i) => { out.push(l); if (inserts.has(i)) out.push(...inserts.get(i)) })
  if (appended.size) {
    out.push('', `# --- Test slot ${slot}: CLI default ports moved up by ${offset} (generated) ---`)
    for (const [sec, ls] of appended) out.push(`[${sec}]`, ...ls, '')
  }
  return `# GENERATED by scripts/test-slot.sh from supabase/config.toml for test slot ${slot}. Do not edit.\n${out.join('\n')}`
}

// node slotConfig.js <slot> <source config.toml> <target config.toml>
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [slot, from, to] = process.argv.slice(2)
  writeFileSync(to, slotConfig(readFileSync(from, 'utf8'), Number(slot)))
}
